// Builds src/pieces/cburnett.css from assets/cburnett/*.svg (see assets/cburnett/NOTICE.md).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { CODES, dataUri, pieceSet } from "./sprite-to-css.mjs";

const root = new URL("../", import.meta.url);

function picture(code) {
  const svg = readFileSync(new URL(`assets/cburnett/${code}.svg`, root), "utf8")
    .replace(/<\?xml[^>]*\?>/, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<!DOCTYPE[^>]*>/, "")
    .replace(/<svg\s([^>]*?)width="45"\s+height="45"/, '<svg $1viewBox="0 0 45 45"');
  if (!svg.includes('viewBox="0 0 45 45"')) throw new Error(`${code}: no viewBox`);
  return dataUri(svg);
}

const images = Object.fromEntries(CODES.map((code) => [code, picture(code)]));
const css = `/* Chess pieces by Colin M.L. Burnett (Cburnett), from Wikimedia Commons, used under the BSD licence. See assets/cburnett/NOTICE.md. Generated by scripts/pieces.mjs. This set is the page's default; the class ls-set-cburnett picks it where another default is loaded. */\n${pieceSet("cburnett", images, true)}`;
mkdirSync(new URL("src/pieces/", root), { recursive: true });
writeFileSync(new URL("src/pieces/cburnett.css", root), css);
console.log(`src/pieces/cburnett.css ${css.length} bytes`);
