// Builds src/pieces/cburnett.css from assets/cburnett/*.svg (see assets/cburnett/NOTICE.md).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const codes = ["wk", "wq", "wr", "wb", "wn", "wp", "bk", "bq", "br", "bb", "bn", "bp"];

function dataUri(code) {
  const svg = readFileSync(new URL(`assets/cburnett/${code}.svg`, root), "utf8")
    .replace(/<\?xml[^>]*\?>/, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<!DOCTYPE[^>]*>/, "")
    .replace(/<svg\s([^>]*?)width="45"\s+height="45"/, '<svg $1viewBox="0 0 45 45"')
    .replace(/>\s+</g, "><")
    .replace(/\s+/g, " ")
    .trim();
  if (!svg.includes('viewBox="0 0 45 45"')) throw new Error(`${code}: no viewBox`);
  return `data:image/svg+xml,${encodeURIComponent(svg).replace(/%20/g, " ").replace(/%3D/g, "=").replace(/%3A/g, ":").replace(/%2F/g, "/").replace(/%2C/g, ",")}`;
}

const rules = codes.map((code) => `.ls-${code} { background-image: url("${dataUri(code)}"); }`);
const css = `/* Chess pieces by Colin M.L. Burnett (Cburnett), from Wikimedia Commons, used under the BSD licence. See assets/cburnett/NOTICE.md. Generated by scripts/pieces.mjs. */\n${rules.join("\n")}\n`;
mkdirSync(new URL("src/pieces/", root), { recursive: true });
writeFileSync(new URL("src/pieces/cburnett.css", root), css);
console.log(`src/pieces/cburnett.css ${css.length} bytes`);
