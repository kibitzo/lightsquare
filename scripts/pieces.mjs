// Builds the package's piece sets:
//   src/pieces/cburnett.css from assets/cburnett/*.svg (see assets/cburnett/NOTICE.md)
//   src/pieces/kibitzo.css from piece-sets/kibitzo.svg (see piece-sets/NOTICE.md)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { CODES, dataUri, pieceSet, spriteToCss } from "./sprite-to-css.mjs";

const root = new URL("../", import.meta.url);

function picture(code) {
  const svg = readFileSync(new URL(`assets/cburnett/${code}.svg`, root), "utf8")
    .replace(/<\?xml[^>]*\?>/, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<!DOCTYPE[^>]*>/, "")
    .replace(/<svg\s([^>]*?)width="45"\s+height="45"/, '<svg $1viewBox="0 0 45 45"');
  if (!svg.includes('viewBox="0 0 45 45"')) throw new Error(`${code}: no viewBox`);
  return dataUri(svg);
}

const images = Object.fromEntries(CODES.map((code) => [code, picture(code)]));
const css = `/* Chess pieces by Colin M.L. Burnett (Cburnett), from Wikimedia Commons, used under the BSD licence. See assets/cburnett/NOTICE.md. Generated by scripts/pieces.mjs. This set is the page's default; the class ls-set-cburnett picks it where another default is loaded. */\n${pieceSet("cburnett", images, true)}`;
mkdirSync(new URL("src/pieces/", root), { recursive: true });
writeFileSync(new URL("src/pieces/cburnett.css", root), css);
console.log(`src/pieces/cburnett.css ${css.length} bytes`);

// The comment starts with /*! so that the build keeps it: the credit travels with the pictures.
export const KIBITZO_CREDIT = "/*! Kibitzo chess pieces, kibitzo.com. (c) 2026 Danubian Research AG. Licence: CC BY 4.0, https://creativecommons.org/licenses/by/4.0/ (give credit). See kibitzo-NOTICE.md beside this file. */";
const kibitzo = `${KIBITZO_CREDIT}\n/* Generated by scripts/pieces.mjs from piece-sets/kibitzo.svg. Loaded, this set is the page's default; the class ls-set-kibitzo picks it where another default is loaded. */\n${spriteToCss(readFileSync(new URL("piece-sets/kibitzo.svg", root), "utf8"), "kibitzo", true)}`;
writeFileSync(new URL("src/pieces/kibitzo.css", root), kibitzo);
console.log(`src/pieces/kibitzo.css ${kibitzo.length} bytes`);
